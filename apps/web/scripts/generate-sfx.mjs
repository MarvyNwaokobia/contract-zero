// Generates the game's recorded-style sound effects from code, so every shipped
// sample is original (no third-party audio). Deterministic: same seed, same file.
//   node scripts/generate-sfx.mjs        (needs ffmpeg on PATH)
// Writes public/sounds/fps/{rifle_1,rifle_2,rifle_3,impact_wall}.mp3
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const RATE = 44100;
function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
/** One-pole low-pass state machine. */
const lowpass = (cut) => { const a = Math.exp(-2 * Math.PI * cut / RATE); let y = 0; return (x) => (y = (1 - a) * x + a * y); };
const highpass = (cut) => { const lp = lowpass(cut); return (x) => x - lp(x); };

function gunshot(seed, pitch) {
  const r = rng(seed);
  const n = Math.floor(RATE * 0.9);
  const out = new Float32Array(n);
  const crackHp = highpass(2500), bodyLp = lowpass(1400 * pitch), tailLp = lowpass(700 * pitch);
  let phase = 0;
  for (let i = 0; i < n; i++) {
    const t = i / RATE;
    const noise = r() * 2 - 1;
    // crack: a very short bright transient
    const crack = crackHp(noise) * Math.exp(-t / 0.004) * 1.4;
    // body: filtered noise with a fast decay
    const body = bodyLp(noise) * Math.exp(-t / 0.05) * 2.2;
    // boom: a falling sine underneath
    const f = (95 * pitch) * Math.exp(-t * 6) + 38;
    phase += (2 * Math.PI * f) / RATE;
    const boom = Math.sin(phase) * Math.exp(-t / 0.12) * 0.9;
    // tail: the report off the surroundings
    const tail = tailLp(noise) * Math.exp(-t / 0.28) * 0.7 * Math.min(1, t / 0.02);
    out[i] = Math.tanh((crack + body + boom + tail) * 1.6) * 0.92;
  }
  return out;
}

function wallImpact(seed) {
  const r = rng(seed);
  const n = Math.floor(RATE * 0.35);
  const out = new Float32Array(n);
  const hp = highpass(1800), lp = lowpass(4200);
  for (let i = 0; i < n; i++) {
    const t = i / RATE;
    const noise = r() * 2 - 1;
    const tick = lp(hp(noise)) * Math.exp(-t / 0.012) * 1.6;
    const ring = (Math.sin(2 * Math.PI * 2350 * t) * 0.35 + Math.sin(2 * Math.PI * 3720 * t) * 0.2) * Math.exp(-t / 0.06);
    const grit = lp(noise) * Math.exp(-t / 0.09) * 0.25;
    out[i] = Math.tanh((tick + ring + grit) * 1.3) * 0.9;
  }
  return out;
}

function wav(samples) {
  const buf = Buffer.alloc(44 + samples.length * 2);
  buf.write('RIFF', 0); buf.writeUInt32LE(36 + samples.length * 2, 4); buf.write('WAVE', 8);
  buf.write('fmt ', 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
  buf.writeUInt32LE(RATE, 24); buf.writeUInt32LE(RATE * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34);
  buf.write('data', 36); buf.writeUInt32LE(samples.length * 2, 40);
  samples.forEach((s, i) => buf.writeInt16LE(Math.max(-32767, Math.min(32767, Math.round(s * 32767))), 44 + i * 2));
  return buf;
}

const dir = mkdtempSync(join(tmpdir(), 'cz-sfx-'));
const files = { rifle_1: gunshot(11, 1.0), rifle_2: gunshot(29, 0.92), rifle_3: gunshot(47, 1.08), impact_wall: wallImpact(5) };
for (const [name, s] of Object.entries(files)) {
  const w = join(dir, `${name}.wav`);
  writeFileSync(w, wav(s));
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', w, '-codec:a', 'libmp3lame', '-b:a', '128k', '-map_metadata', '-1', '-metadata', 'comment=CONTRACT ZERO original, generated by scripts/generate-sfx.mjs', new URL(`../public/sounds/fps/${name}.mp3`, import.meta.url).pathname]);
  console.log('wrote', `public/sounds/fps/${name}.mp3`);
}
rmSync(dir, { recursive: true, force: true });
